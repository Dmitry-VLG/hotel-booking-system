create table users (
  id bigint generated by default as identity primary key,
  username varchar(64) not null unique,
  password varchar(100) not null,
  role varchar(10) not null check (role in ('USER','ADMIN')),
  active boolean not null,
  created_at timestamp with time zone not null,
  version bigint not null
);
create table bookings (
  id uuid primary key,
  user_id bigint not null references users(id),
  room_id bigint,
  hotel_id bigint,
  auto_select boolean not null,
  start_date date not null,
  end_date date not null,
  status varchar(16) not null check (status in ('PENDING','CONFIRMED','CANCELLED')),
  created_at timestamp with time zone not null,
  updated_at timestamp with time zone not null,
  deadline_at timestamp with time zone not null,
  reservation_id uuid,
  saga_phase varchar(24) not null,
  compensation_status varchar(16) not null,
  release_reason varchar(30),
  request_key varchar(100) not null,
  payload_hash varchar(64) not null,
  cached_status integer,
  cached_body clob,
  retry_count integer not null,
  next_retry_at timestamp with time zone,
  version bigint not null,
  constraint uq_booking_request unique (user_id, request_key),
  check (start_date < end_date),
  check (status <> 'CONFIRMED' or (room_id is not null and reservation_id is not null))
);
create index idx_booking_history on bookings(user_id, created_at, id);
create index idx_booking_pending on bookings(status, deadline_at);
create index idx_booking_compensation on bookings(status, compensation_status, next_retry_at);
create index idx_booking_room_dates on bookings(room_id, start_date, end_date);
