create table hotels (
  id bigint generated by default as identity primary key,
  name varchar(120) not null,
  address varchar(250) not null,
  active boolean not null,
  version bigint not null
);
create table rooms (
  id bigint generated by default as identity primary key,
  hotel_id bigint not null references hotels(id),
  number varchar(30) not null,
  available boolean not null,
  times_booked bigint not null check (times_booked >= 0),
  active boolean not null,
  version bigint not null,
  constraint uq_room_number unique (hotel_id, number)
);
create table room_reservations (
  reservation_id uuid primary key,
  booking_id uuid not null,
  room_id bigint not null references rooms(id),
  start_date date not null,
  end_date date not null,
  state varchar(20) not null check (state in ('HELD','COMMITTED','RELEASED','EXPIRED')),
  expires_at timestamp with time zone,
  counted boolean not null,
  release_reason varchar(30),
  created_at timestamp with time zone not null,
  version bigint not null,
  check (start_date < end_date)
);
create index idx_rooms_search on rooms(hotel_id, active, available, times_booked, id);
create index idx_reservations_dates on room_reservations(room_id, state, start_date, end_date);
create index idx_reservations_expiry on room_reservations(state, expires_at);
create index idx_reservations_booking on room_reservations(booking_id);
